"""Render deterministic, real Live2D preview PNGs during a resource build.

The previews come from the same provisioned Cubism Web runtime used by the
catalogue.  They are deliberately generated by a browser WebGL canvas rather
than reusing a character face image or texture sheet.  A build without a local
headless Chrome or a validated Cubism provision remains valid, but records an
explicit unavailable preview instead of claiming a substitute is a model
render.
"""

from __future__ import annotations

import json
import os
import signal
import shutil
import subprocess
import tempfile
import threading
import time
from hashlib import sha256
from base64 import b64decode
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import dataclass, field
from http import HTTPStatus
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from io import BytesIO
from pathlib import Path, PurePosixPath
from typing import Any
from urllib.parse import unquote, urlencode, urlsplit

from PIL import Image, UnidentifiedImageError

from build.preview_image import crop_transparent_png
from core.paths import PROJECT_ROOT


PREVIEW_SCHEMA = "haneoka-live2d-preview-v3"
PREVIEW_SIZE = 512
PREVIEW_TIMEOUT_SECONDS = 30
PREVIEW_ATTEMPTS = 2
# Without a screenshot task, headless Chrome exits after the initial document
# load. Keep the page alive long enough to finish its asynchronous model load;
# the viewer remains paused throughout virtual-time advancement.
PREVIEW_VIRTUAL_TIME_BUDGET_MS = 10_000
PREVIEW_POLICY_ENV = "HANEOKA_MODEL_PREVIEW_POLICY"
PREVIEW_WORKERS_ENV = "HANEOKA_MODEL_PREVIEW_WORKERS"
CHROME_PATH_ENV = "HANEOKA_CHROME_PATH"
_PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"
_MAX_PREVIEW_PNG_BYTES = 8 * 1024 * 1024
_MAX_PREVIEW_BASE64_BYTES = 4 * ((_MAX_PREVIEW_PNG_BYTES + 2) // 3)
_MAX_PREVIEW_POST_BYTES = 12 * 1024 * 1024


def _safe_relative(value: str) -> PurePosixPath | None:
    path = PurePosixPath(value.replace("\\", "/").strip("/"))
    if not path.parts or path.is_absolute() or any(part in ("", ".", "..") for part in path.parts):
        return None
    return path


def _chrome_binary() -> str | None:
    configured = os.environ.get(CHROME_PATH_ENV, "").strip()
    candidates = [
        configured,
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        shutil.which("google-chrome") or "",
        shutil.which("google-chrome-stable") or "",
        shutil.which("chromium") or "",
        shutil.which("chromium-browser") or "",
    ]
    for candidate in candidates:
        if candidate and Path(candidate).is_file():
            return candidate
    return None


def _decode_preview_png(value: object) -> bytes:
    """Decode the only image form accepted from the loopback preview page."""

    if not isinstance(value, str) or not value.startswith("data:image/png;base64,"):
        raise ValueError("preview page did not provide a PNG data URL")
    encoded = value.removeprefix("data:image/png;base64,")
    if not encoded or len(encoded) > _MAX_PREVIEW_BASE64_BYTES:
        raise ValueError("preview page PNG payload is too large")
    try:
        payload = b64decode(encoded, validate=True)
    except ValueError as error:
        raise ValueError("preview page PNG payload is not valid base64") from error
    if len(payload) > _MAX_PREVIEW_PNG_BYTES:
        raise ValueError("preview page PNG payload is too large")
    if not payload.startswith(_PNG_SIGNATURE):
        raise ValueError("preview page did not provide a PNG")
    return payload


def _validate_preview_canvas(payload: bytes) -> None:
    """Reject browser failures before they can become a rendered preview.

    A real Cubism canvas is deliberately transparent around its 93%-framed
    model.  That lets us distinguish an actual model image from a blank render
    or Chromium's opaque navigation error page even though both are valid PNG
    files.  The fixed source dimensions also guard against a stale or unrelated
    canvas being posted to this local endpoint.
    """

    try:
        with Image.open(BytesIO(payload)) as source:
            if source.format != "PNG":
                raise ValueError("preview page did not provide a PNG")
            source.load()
            image = source.convert("RGBA")
    except (OSError, UnidentifiedImageError) as error:
        raise ValueError("preview page returned an unreadable PNG") from error

    if image.size != (PREVIEW_SIZE, PREVIEW_SIZE):
        raise ValueError("preview page returned an unexpected canvas size")
    alpha = image.getchannel("A")
    bounds = alpha.getbbox()
    if bounds is None:
        raise ValueError("preview page returned no visible model pixels")
    if alpha.getextrema()[0] != 0 or bounds == (0, 0, PREVIEW_SIZE, PREVIEW_SIZE):
        raise ValueError("preview page returned an opaque full-canvas image")


def _static_model3_document(payload: bytes) -> bytes:
    """Return a preview-only model descriptor with every dynamic channel absent.

    The provisioned viewer intentionally supports motion and physics for the
    interactive catalogue, but its public ``load`` API does not expose a
    physics switch.  Supplying this descriptor only through the private
    loopback preview server is a narrow way to make the static-build contract
    absolute without modifying the integrity-locked runtime shared by playback.
    Pose remains available because it controls authored part visibility, not an
    animation timeline.
    """

    try:
        document = json.loads(payload.decode("utf-8"))
    except (UnicodeDecodeError, json.JSONDecodeError) as error:
        raise ValueError("Live2D model descriptor is invalid") from error
    if not isinstance(document, dict):
        raise ValueError("Live2D model descriptor is not an object")
    references = document.get("FileReferences")
    if not isinstance(references, dict):
        raise ValueError("Live2D model descriptor has no file references")
    static_references = dict(references)
    static_references.pop("Physics", None)
    static_references["Motions"] = {"Motion": []}
    static_references["Expressions"] = []
    static_document = {**document, "FileReferences": static_references}
    return json.dumps(static_document, ensure_ascii=False, separators=(",", ":")).encode("utf-8")


@dataclass
class _PreviewServer:
    layout_root: Path
    public_root: Path
    server: str
    _states: dict[str, dict[str, Any]] = field(default_factory=dict)
    _condition: threading.Condition = field(default_factory=threading.Condition)
    _http: ThreadingHTTPServer | None = None
    _thread: threading.Thread | None = None

    def __enter__(self) -> "_PreviewServer":
        parent = self

        class Handler(BaseHTTPRequestHandler):
            def log_message(self, _format: str, *_args: object) -> None:
                # Browser asset traffic is noisy and never useful in a build log.
                return

            def _asset_file(self) -> Path | None:
                path = unquote(urlsplit(self.path).path)
                routes = (
                    (f"/assets/{parent.server}/", parent.layout_root / "assets"),
                    (f"/runtime/{parent.server}/", parent.layout_root / "runtime"),
                    ("/cubism-runtime/", parent.public_root / "cubism-runtime"),
                    ("/Core/", parent.public_root / "Core"),
                )
                for prefix, root in routes:
                    if not path.startswith(prefix):
                        continue
                    relative = _safe_relative(path.removeprefix(prefix))
                    if relative is None:
                        return None
                    candidate = root.joinpath(*relative.parts)
                    try:
                        candidate.resolve().relative_to(root.resolve())
                    except ValueError:
                        return None
                    return candidate if candidate.is_file() else None
                return None

            def do_GET(self) -> None:  # noqa: N802 - BaseHTTPRequestHandler API
                path = urlsplit(self.path).path
                if path == "/__haneoka_live2d_preview.html":
                    content = _PREVIEW_PAGE.encode("utf-8")
                    self.send_response(HTTPStatus.OK)
                    self.send_header("Content-Type", "text/html; charset=utf-8")
                    self.send_header("Content-Length", str(len(content)))
                    self.end_headers()
                    self.wfile.write(content)
                    return
                file = self._asset_file()
                if file is None:
                    self.send_error(HTTPStatus.NOT_FOUND)
                    return
                is_static_model_request = (
                    path.startswith(f"/runtime/{parent.server}/live2d/")
                    and (file.name.casefold() == "model3.json" or file.name.casefold().endswith(".model3.json"))
                )
                content_type = {
                    ".js": "text/javascript; charset=utf-8",
                    ".mjs": "text/javascript; charset=utf-8",
                    ".json": "application/json; charset=utf-8",
                    ".png": "image/png",
                    ".moc3": "application/octet-stream",
                }.get(file.suffix.casefold(), "application/octet-stream")
                try:
                    content = _static_model3_document(file.read_bytes()) if is_static_model_request else file.read_bytes()
                except ValueError:
                    self.send_error(HTTPStatus.INTERNAL_SERVER_ERROR)
                    return
                self.send_response(HTTPStatus.OK)
                self.send_header("Content-Type", content_type)
                self.send_header("Content-Length", str(len(content)))
                self.end_headers()
                self.wfile.write(content)

            def do_POST(self) -> None:  # noqa: N802 - BaseHTTPRequestHandler API
                if urlsplit(self.path).path != "/__haneoka_live2d_preview_state":
                    self.send_error(HTTPStatus.NOT_FOUND)
                    return
                try:
                    length = int(self.headers.get("Content-Length") or "0")
                    if length <= 0 or length > _MAX_PREVIEW_POST_BYTES:
                        self.send_error(HTTPStatus.REQUEST_ENTITY_TOO_LARGE)
                        return
                    value = json.loads(self.rfile.read(length).decode("utf-8"))
                    if not isinstance(value, dict):
                        raise ValueError("invalid preview state")
                    key = str(value.get("key") or "").strip()
                    status = str(value.get("status") or "").strip()
                    if not key or status not in {"ready", "error"}:
                        raise ValueError("invalid preview state")
                    png = _decode_preview_png(value.get("image")) if status == "ready" else None
                    with parent._condition:
                        parent._states[key] = {
                            "status": status,
                            "message": str(value.get("message") or "")[:512],
                            **({"png": png} if png is not None else {}),
                        }
                        parent._condition.notify_all()
                except (UnicodeDecodeError, ValueError, json.JSONDecodeError):
                    self.send_error(HTTPStatus.BAD_REQUEST)
                    return
                self.send_response(HTTPStatus.NO_CONTENT)
                self.end_headers()

        self._http = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
        self._thread = threading.Thread(target=self._http.serve_forever, name="live2d-preview-server", daemon=True)
        self._thread.start()
        return self

    def __exit__(self, *_: object) -> None:
        if self._http is not None:
            self._http.shutdown()
            self._http.server_close()
        if self._thread is not None:
            self._thread.join(timeout=2)

    @property
    def origin(self) -> str:
        if self._http is None:
            raise RuntimeError("preview server is not running")
        host, port = self._http.server_address[:2]
        return f"http://{host}:{port}"

    def state(self, key: str) -> dict[str, Any] | None:
        with self._condition:
            state = self._states.get(key)
            return dict(state) if state is not None else None

    def clear_state(self, key: str) -> None:
        with self._condition:
            self._states.pop(key, None)


_PREVIEW_PAGE = f"""<!doctype html>
<meta charset="utf-8">
<style>
  html, body, canvas {{ width: {PREVIEW_SIZE}px; height: {PREVIEW_SIZE}px; margin: 0; padding: 0; overflow: hidden; background: transparent; }}
  canvas {{ display: block; }}
</style>
<canvas id="preview" width="{PREVIEW_SIZE}" height="{PREVIEW_SIZE}"></canvas>
<script src="/Core/live2dcubismcore.js"></script>
<script type="module">
  import {{ CubismModelViewer }} from "/cubism-runtime/vega-cubism-web-runtime.mjs";
  const params = new URLSearchParams(location.search);
  const key = params.get("key") || "";
  const modelUrl = params.get("model") || "";
  const report = async (status, message = "", image = "") => {{
    const response = await fetch("/__haneoka_live2d_preview_state", {{
      method: "POST",
      headers: {{ "content-type": "application/json" }},
      body: JSON.stringify({{ key, status, message, image }}),
    }});
    if (!response.ok) throw new Error(`preview state was rejected (${{response.status}})`);
  }};
  try {{
    const canvas = document.querySelector("#preview");
    const viewer = new CubismModelViewer({{ canvas, onError: (error) => report("error", String(error)) }});
    viewer.setSize({PREVIEW_SIZE}, {PREVIEW_SIZE});
    // Freeze before loading, then explicitly clear the possible playback
    // channels after model creation. Do not supply a default motion or
    // expression: the captured frame is the authored time-zero pose only.
    viewer.setPaused(true);
    viewer.setBreathEnabled(false);
    viewer.setEyeBlinkEnabled(false);
    await viewer.load({{ modelUrl }});
    viewer.stopMotions();
    viewer.setLoopMotion(null);
    viewer.setPaused(true);
    viewer.setBreathEnabled(false);
    viewer.setEyeBlinkEnabled(false);
    viewer.renderNow();
    // A direct canvas export is ordered after the model's static render. This
    // avoids Chrome's CLI screenshot race, which can capture a blank frame or
    // the browser's navigation-error page before a model finishes loading.
    const image = canvas.toDataURL("image/png");
    document.title = "haneoka-live2d-preview-ready";
    await report("ready", "", image);
  }} catch (error) {{
    document.title = "haneoka-live2d-preview-error";
    try {{
      await report("error", error instanceof Error ? error.message : String(error));
    }} catch {{
      // The builder observes browser termination and will record this attempt
      // as unavailable if even the compact error state cannot be delivered.
    }}
  }}
</script>
"""


def _rendered_initial_preview(
    server: str,
    key: str,
    width: int,
    height: int,
    content_sha256: str | None = None,
) -> dict[str, Any]:
    """Describe a PNG captured at the model's authored time-zero state.

    Keep these markers deliberately redundant.  They are user-facing
    provenance, and they prevent an older cached idle/motion render from being
    silently reused after the preview policy changes.
    """

    preview: dict[str, Any] = {
        "status": "rendered",
        "runtime": f"/runtime/{server}/previews/live2d/{key}.png",
        "width": width,
        "height": height,
        "state": "initial",
        "animation": "none",
        "expression": "none",
        "elapsedMilliseconds": 0,
        "renderer": "cubism-web-runtime",
    }
    if content_sha256 is not None:
        preview["sha256"] = content_sha256
    return preview


def _is_initial_static_preview(preview: object, expected_runtime: str) -> bool:
    """Return whether cached provenance proves this is a static initial frame."""

    return bool(
        isinstance(preview, dict)
        and preview.get("status") == "rendered"
        and preview.get("runtime") == expected_runtime
        and preview.get("state") == "initial"
        and preview.get("animation") == "none"
        and preview.get("expression") == "none"
        and preview.get("elapsedMilliseconds") == 0
        and preview.get("renderer") == "cubism-web-runtime"
        and isinstance(preview.get("width"), int)
        and preview["width"] > 0
        and isinstance(preview.get("height"), int)
        and preview["height"] > 0
    )


def _cached_preview_image_matches(payload: bytes, preview: dict[str, Any]) -> bool:
    """Ensure cache metadata still describes a transparent cropped PNG."""

    try:
        with Image.open(BytesIO(payload)) as source:
            if source.format != "PNG":
                return False
            source.load()
            image = source.convert("RGBA")
    except (OSError, UnidentifiedImageError):
        return False
    if image.size != (preview["width"], preview["height"]):
        return False
    alpha = image.getchannel("A")
    bounds = alpha.getbbox()
    return bool(
        bounds is not None
        and alpha.getextrema()[0] == 0
        and bounds != (0, 0, image.width, image.height)
    )


def _preview_model(
    chrome: str,
    server: _PreviewServer,
    temporary: Path,
    key: str,
    model: dict[str, Any],
    output: Path,
) -> tuple[str, dict[str, Any]]:
    runtime = model.get("runtime") if isinstance(model.get("runtime"), dict) else {}
    model_url = str(runtime.get("model") or "").strip()
    if not model_url.startswith(f"/runtime/{server.server}/live2d/"):
        return key, {"status": "unavailable", "reason": "model-runtime-url-missing"}
    if urlsplit(model_url).query or urlsplit(model_url).fragment:
        return key, {"status": "unavailable", "reason": "model-runtime-url-invalid"}
    output.parent.mkdir(parents=True, exist_ok=True)
    output.unlink(missing_ok=True)
    server.clear_state(key)
    profile = temporary / f"profile-{key}"
    query = urlencode({"key": key, "model": model_url})
    url = f"{server.origin}/__haneoka_live2d_preview.html?{query}"
    command = [
        chrome,
        "--headless=new",
        "--hide-scrollbars",
        "--no-first-run",
        "--no-default-browser-check",
        "--disable-background-networking",
        "--disable-component-update",
        "--disable-dev-shm-usage",
        "--enable-webgl",
        "--ignore-gpu-blocklist",
        "--use-angle=swiftshader",
        "--force-color-profile=srgb",
        "--default-background-color=00000000",
        f"--window-size={PREVIEW_SIZE},{PREVIEW_SIZE}",
        f"--virtual-time-budget={PREVIEW_VIRTUAL_TIME_BUDGET_MS}",
        f"--user-data-dir={profile}",
        url,
    ]
    try:
        process = subprocess.Popen(
            command,
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
            start_new_session=True,
        )
    except OSError as error:
        return key, {"status": "unavailable", "reason": "headless-render-failed", "detail": str(error)[:512]}

    state: dict[str, Any] | None = None
    deadline = time.monotonic() + PREVIEW_TIMEOUT_SECONDS
    try:
        while time.monotonic() < deadline:
            state = server.state(key)
            if state is not None and (
                state.get("status") == "error" or (state.get("status") == "ready" and isinstance(state.get("png"), bytes))
            ):
                break
            if process.poll() is not None:
                break
            time.sleep(0.05)
    finally:
        if process.poll() is None:
            try:
                os.killpg(process.pid, signal.SIGTERM)
            except ProcessLookupError:
                pass
        try:
            process.wait(timeout=3)
        except subprocess.TimeoutExpired:
            try:
                os.killpg(process.pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
            process.wait(timeout=3)

    state = server.state(key)
    payload = state.get("png") if state and state.get("status") == "ready" else None
    if isinstance(payload, bytes):
        try:
            _validate_preview_canvas(payload)
            cropped = crop_transparent_png(payload)
        except ValueError as error:
            return key, {
                "status": "unavailable",
                "reason": "headless-render-invalid-image",
                "detail": str(error)[:512],
            }
        output.write_bytes(cropped.png)
        return key, _rendered_initial_preview(
            server.server,
            key,
            cropped.width,
            cropped.height,
            sha256(cropped.png).hexdigest(),
        )
    output.unlink(missing_ok=True)
    detail = str((state or {}).get("message") or "")[:512]
    return key, {"status": "unavailable", "reason": "headless-render-failed", **({"detail": detail} if detail else {})}


def _preview_model_with_retry(
    chrome: str,
    server: _PreviewServer,
    temporary: Path,
    key: str,
    model: dict[str, Any],
    output: Path,
) -> tuple[str, dict[str, Any]]:
    """Retry a browser startup failure once before declaring a preview absent.

    The source graph has already been validated by the Live2D builder.  A
    short, bounded retry handles a transient headless Chrome/GPU startup race
    without ever replacing the model with unrelated artwork.
    """

    last: tuple[str, dict[str, Any]] | None = None
    for _attempt in range(PREVIEW_ATTEMPTS):
        last = _preview_model(chrome, server, temporary, key, model, output)
        if last[1].get("status") == "rendered":
            return last
    return last or (key, {"status": "unavailable", "reason": "headless-render-failed"})


def _cached_previews(
    layout: Any,
    server: str,
    source_id: str,
    models: dict[str, dict[str, Any]],
) -> dict[str, dict[str, Any]]:
    """Reuse only verified previews produced for this exact immutable input.

    A full preview pass starts one Chromium process per model.  Keeping a
    validated result lets a re-run retry only transient failures; a different
    source id never participates in this cache.
    """

    file = layout.metadata / "live2d.json"
    try:
        document = json.loads(file.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError):
        return {}
    if (
        not isinstance(document, dict)
        or document.get("schema") != "haneoka-live2d-build-v1"
        or document.get("previewSchema") != PREVIEW_SCHEMA
        or document.get("server") != server
        or document.get("sourceId") != source_id
    ):
        return {}
    previous = document.get("models")
    if not isinstance(previous, dict):
        return {}
    output: dict[str, dict[str, Any]] = {}
    for key in models:
        model = previous.get(key)
        preview = model.get("preview") if isinstance(model, dict) else None
        expected = f"/runtime/{server}/previews/live2d/{key}.png"
        target = layout.runtime / "previews" / "live2d" / f"{key}.png"
        if _is_initial_static_preview(preview, expected) and target.is_file():
            payload = target.read_bytes()
            if _cached_preview_image_matches(payload, preview):
                cached = dict(preview)
                # Older v3 metadata has the same static provenance but predates
                # the cache fingerprint. Reuse its verified PNG and enrich the
                # record instead of paying for another Chromium render.
                cached["sha256"] = sha256(payload).hexdigest()
                output[key] = cached
    return output


def _prune_preview_outputs(preview_root: Path, keep: set[str]) -> None:
    """Remove only obsolete PNGs owned by this builder's flat output directory.

    The directory can survive a prior build even when this build deliberately
    disables previews or cannot provision Chromium.  Leaving those files in
    ``runtime`` would make an old idle render ship in a release despite the
    new metadata correctly saying that no preview is available.  Do not remove
    directories or non-PNG files here: this is intentionally scoped to the
    exact derivative names emitted by this module.
    """

    if not preview_root.exists():
        return
    if not preview_root.is_dir():
        raise ValueError(f"Live2D preview output root is not a directory: {preview_root}")
    for candidate in preview_root.glob("*.png"):
        if candidate.stem not in keep:
            candidate.unlink()


def build_live2d_previews(
    layout: Any,
    server: str,
    source_id: str,
    models: dict[str, dict[str, Any]],
) -> dict[str, dict[str, Any]]:
    """Attach real preview metadata to each model, without pretending on failure."""

    policy = os.environ.get(PREVIEW_POLICY_ENV, "optional").strip().casefold()
    if policy not in {"optional", "required", "off"}:
        raise ValueError(f"{PREVIEW_POLICY_ENV} must be optional, required, or off")
    unavailable = {key: {"status": "unavailable", "reason": "preview-rendering-disabled"} for key in models}
    preview_root = layout.runtime / "previews" / "live2d"
    if policy == "off":
        _prune_preview_outputs(preview_root, set())
        return unavailable
    chrome = _chrome_binary()
    provision = PROJECT_ROOT / "public" / "cubism-runtime" / "vega-cubism-web-runtime.mjs"
    if not chrome or not provision.is_file():
        _prune_preview_outputs(preview_root, set())
        if policy == "required":
            missing = "Chrome" if not chrome else "Cubism web runtime provision"
            raise RuntimeError(f"Live2D preview rendering requires {missing}")
        reason = "headless-chrome-unavailable" if not chrome else "cubism-runtime-unavailable"
        return {key: {"status": "unavailable", "reason": reason} for key in models}

    workers = max(1, min(4, int(os.environ.get(PREVIEW_WORKERS_ENV, "3") or "3")))
    preview_root.mkdir(parents=True, exist_ok=True)
    result = _cached_previews(layout, server, source_id, models)
    _prune_preview_outputs(preview_root, set(models))
    with tempfile.TemporaryDirectory(prefix="haneoka-live2d-preview-") as temp_dir, _PreviewServer(
        layout.root, PROJECT_ROOT / "public", server
    ) as preview_server:
        temporary = Path(temp_dir)
        with ThreadPoolExecutor(max_workers=workers) as executor:
            futures = [
                executor.submit(
                    _preview_model_with_retry,
                    chrome,
                    preview_server,
                    temporary,
                    key,
                    model,
                    preview_root / f"{key}.png",
                )
                for key, model in sorted(models.items())
                if key not in result
            ]
            for future in as_completed(futures):
                key, preview = future.result()
                result[key] = preview
    return {key: result.get(key, unavailable[key]) for key in models}
