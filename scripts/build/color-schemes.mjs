#!/usr/bin/env node
// Generates the Material 3 dynamic color schemes that the site can be "tuned" to.
// Output is committed (packages/design-tokens/src/schemes.css) so the frontend build
// never computes color at runtime: switching a tuning only flips `data-seed` on <html>.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  DynamicScheme,
  Hct,
  MaterialDynamicColors,
  SchemeFidelity,
  TonalPalette,
  argbFromHex,
  hexFromArgb,
} from "@material/material-color-utilities";
// `Variant` is not exported from the package root in 0.3.0; TONAL_SPOT is enum value 2.
const Variant = { TONAL_SPOT: 2 };

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const output = path.join(root, "packages/design-tokens/src/schemes.css");

/** The brand triad comes from the favicon; bands come from MasterBand.color. */
const BRAND = { primary: "#31356e", secondary: "#31356e", tertiary: "#79bbc8" };
export const SEEDS = [
  { id: "haneoka", source: BRAND.primary },
  { id: "band-1", source: "#3388bb" },
  { id: "band-2", source: "#881144" },
  { id: "band-3", source: "#ff7788" },
  { id: "band-4", source: "#aa22ee" },
  { id: "band-5", source: "#ffaa33" },
];

const ROLES = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "error",
  "onError",
  "errorContainer",
  "onErrorContainer",
  "primaryFixed",
  "primaryFixedDim",
  "onPrimaryFixed",
  "onPrimaryFixedVariant",
  "secondaryFixed",
  "secondaryFixedDim",
  "onSecondaryFixed",
  "onSecondaryFixedVariant",
  "tertiaryFixed",
  "tertiaryFixedDim",
  "onTertiaryFixed",
  "onTertiaryFixedVariant",
  "background",
  "onBackground",
  "surface",
  "surfaceDim",
  "surfaceBright",
  "surfaceContainerLowest",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "surfaceContainerHighest",
  "onSurface",
  "surfaceVariant",
  "onSurfaceVariant",
  "outline",
  "outlineVariant",
  "inverseSurface",
  "inverseOnSurface",
  "inversePrimary",
  "surfaceTint",
  "shadow",
  "scrim",
];
const kebab = (value) => value.replace(/[A-Z]/g, (letter) => `-${letter.toLowerCase()}`);

function brandScheme(isDark) {
  const palette = (hex) => TonalPalette.fromHct(Hct.fromInt(argbFromHex(hex)));
  const source = Hct.fromInt(argbFromHex(BRAND.primary));
  return new DynamicScheme({
    sourceColorArgb: source.toInt(),
    variant: Variant.TONAL_SPOT,
    contrastLevel: 0,
    isDark,
    // Shared indigo surfaces with a cyan tertiary accent.
    primaryPalette: TonalPalette.fromHueAndChroma(source.hue, Math.max(source.chroma, 36)),
    secondaryPalette: TonalPalette.fromHueAndChroma(palette(BRAND.secondary).hue, 16),
    tertiaryPalette: TonalPalette.fromHueAndChroma(palette(BRAND.tertiary).hue, 32),
    neutralPalette: TonalPalette.fromHueAndChroma(source.hue, 4),
    neutralVariantPalette: TonalPalette.fromHueAndChroma(source.hue, 8),
  });
}

function schemeFor(seed, isDark) {
  if (seed.id === "haneoka") return brandScheme(isDark);
  return new SchemeFidelity(Hct.fromInt(argbFromHex(seed.source)), isDark, 0);
}

function roleBlock(scheme) {
  return ROLES.map(
    (role) => `  --md-sys-color-${kebab(role)}: ${hexFromArgb(MaterialDynamicColors[role].getArgb(scheme))};`,
  ).join("\n");
}

/** Identity swatches retain the source colour; UI roles carry contrast-adjusted tones. */
function bandBlock(isDark) {
  return SEEDS.filter((seed) => seed.id !== "haneoka")
    .map((seed) => {
      const hct = Hct.fromInt(argbFromHex(seed.source));
      const palette = TonalPalette.fromHueAndChroma(hct.hue, Math.max(hct.chroma, 48));
      return [
        `  --md-ref-${seed.id}: ${seed.source};`,
        `  --md-ref-${seed.id}-container: ${hexFromArgb(palette.tone(isDark ? 30 : 90))};`,
        `  --md-ref-${seed.id}-on-container: ${hexFromArgb(palette.tone(isDark ? 90 : 20))};`,
      ].join("\n");
    })
    .join("\n");
}

const dark = (selector) => `${selector}[data-theme="dark"], ${selector}[data-ui-resolved-theme="dark"]`;
const blocks = [
  "/* Generated by scripts/build/color-schemes.mjs — do not edit by hand. */",
  "/* Material 3 dynamic color. Band schemes preserve their source identity. */",
  `:root {\n${roleBlock(brandScheme(false))}\n${bandBlock(false)}\n}`,
  `${dark(":root")} {\n  color-scheme: dark;\n${roleBlock(brandScheme(true))}\n${bandBlock(true)}\n}`,
];
for (const seed of SEEDS.filter((entry) => entry.id !== "haneoka")) {
  const selector = `:root[data-seed="${seed.id}"]`;
  blocks.push(`${selector} {\n${roleBlock(schemeFor(seed, false))}\n}`);
  blocks.push(`${dark(selector)} {\n${roleBlock(schemeFor(seed, true))}\n}`);
}
// theme-color meta values (top app bar surface) per seed, consumed by the boot script.
const meta = Object.fromEntries(
  SEEDS.map((seed) => {
    return [
      seed.id,
      [false, true].map((isDark) =>
        hexFromArgb(MaterialDynamicColors.surfaceContainer.getArgb(schemeFor(seed, isDark))),
      ),
    ];
  }),
);
blocks.push(`/* theme-color: ${JSON.stringify(meta)} */`);
// Format with the repository's Prettier config so `pnpm format:check` stays green.
const prettier = await import("prettier");
const options = (await prettier.resolveConfig(output)) ?? {};
fs.writeFileSync(output, await prettier.format(`${blocks.join("\n\n")}\n`, { ...options, filepath: output }));
console.log(`wrote ${path.relative(root, output)}`);
console.log(JSON.stringify(meta));
